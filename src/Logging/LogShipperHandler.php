<?php

declare(strict_types=1);

namespace AdminIntelligence\LogShipper\Logging;

use AdminIntelligence\LogShipper\Buffer\LogBufferInterface;
use AdminIntelligence\LogShipper\Jobs\Concerns\ShipsLogs;
use AdminIntelligence\LogShipper\Jobs\ShipLogJob;
use AdminIntelligence\LogShipper\Utils\IpObfuscator;
use AdminIntelligence\LogShipper\Utils\Sanitizer;
use Closure;
use DateTimeZone;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Request;
use Illuminate\Support\Facades\Route;
use JsonSerializable;
use Monolog\Handler\AbstractProcessingHandler;
use Monolog\Level;
use Monolog\LogRecord;
use PDO;
use PDOStatement;
use ReflectionClass;
use Throwable;

class LogShipperHandler extends AbstractProcessingHandler
{
    use ShipsLogs;

    /**
     * The log server's max: rules (characters) for string fields; longer values get a 422.
     */
    protected const FIELD_LIMITS = [
        'message' => 65535,
        'channel' => 255,
        'user_id' => 255,
        'ip_address' => 45,
        'user_agent' => 1024,
        'request_url' => 65535,
        'route_name' => 255,
        'controller_action' => 255,
        'app_env' => 50,
        'referrer' => 2048,
    ];

    /**
     * The log server only accepts these request methods; anything else gets a 422.
     */
    protected const REQUEST_METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'];

    protected const MAX_TRACE_FRAMES = 50;

    protected const MAX_PREVIOUS_DEPTH = 3;

    public function __construct(Level $level = Level::Error, bool $bubble = true)
    {
        parent::__construct($level, $bubble);
    }

    protected function write(LogRecord $record): void
    {
        try {
            $this->ship($record);
        } catch (Throwable) {
            // Logging must never throw into the host app. Never call Log:: here: it would recurse.
        }
    }

    protected function ship(LogRecord $record): void
    {
        if (!config('log-shipper.enabled', true)) {
            return;
        }

        // Unconfigured app: the job would drop the log anyway, so skip the buffer and the queue
        if (empty(config('log-shipper.api_key')) || empty(config('log-shipper.api_endpoint'))) {
            return;
        }

        // Prevent infinite loops: Do not ship logs that are about shipping failures
        if (isset($record->context['log_shipper_failure'])) {
            return;
        }

        // Prevent infinite loops: Do not ship logs generated by the package's own jobs
        if ($this->isRecursiveLog($record)) {
            return;
        }

        // Breaker open: keep the log locally instead of dropping it
        if (config('log-shipper.circuit_breaker.enabled', true) && Cache::has('log_shipper_dead_until')) {
            $context = $this->sanitize($this->filterSerializable($record->context));
            $this->writeFallback(strtolower($record->level->name), $record->message, $context, 'circuit breaker open');

            return;
        }

        $payload = $this->buildPayload($record);
        $sanitizedPayload = $this->sanitize($payload);

        // Clamp after sanitizing: URL redaction can make a query value longer ("a" -> "[REDACTED]")
        foreach (self::FIELD_LIMITS as $field => $max) {
            if (is_string($sanitizedPayload[$field] ?? null)) {
                $sanitizedPayload[$field] = mb_substr($sanitizedPayload[$field], 0, $max);
            }
        }

        // Replace invalid UTF-8 (and NAN/INF, which become 0) once, so the size check,
        // the buffer and the queue all get encodable data
        $jsonPayload = json_encode($sanitizedPayload, JSON_INVALID_UTF8_SUBSTITUTE | JSON_PARTIAL_OUTPUT_ON_ERROR);

        // If json_encode fails, continue anyway (better to try sending than silently fail)
        if ($jsonPayload !== false) {
            $sanitizedPayload = json_decode($jsonPayload, true);
            $payloadSize = strlen($jsonPayload);

            // SECURITY: Prevent DoS by limiting payload size (default 1MB)
            if ($payloadSize > config('log-shipper.max_payload_size', 1048576)) {
                // Context must stay an array: the server validates it as nullable|array
                $sanitizedPayload['context'] = ['_truncated' => true, '_original_size' => $payloadSize];
                $sanitizedPayload['extra'] = ['_truncated' => true];
                $sanitizedPayload['_truncated'] = true;
                $sanitizedPayload['_original_size'] = $payloadSize;
            }
        }

        // One log counts at most once toward the circuit breaker
        $failureRecorded = false;

        // Batch Shipping
        if (config('log-shipper.batch.enabled', false)) {
            try {
                /** @var LogBufferInterface $buffer */
                $buffer = app(LogBufferInterface::class);
                $buffer->push($sanitizedPayload);

                return;
            } catch (Throwable $e) {
                // If buffer fails, fall back to direct shipping
                $this->recordFailure($e);
                $failureRecorded = true;
            }
        }

        $connection = config('log-shipper.queue_connection', 'default');
        $queue = config('log-shipper.queue_name', 'default');

        if ($connection === 'default') {
            $connection = config('queue.default');
        }

        try {
            ShipLogJob::dispatch($sanitizedPayload)
                ->onConnection($connection)
                ->onQueue($queue);
        } catch (Throwable $e) {
            // On a sync queue this is the job's own failure: the job already counted it
            // and its failed() already wrote it to the fallback channel.
            if (config("queue.connections.{$connection}.driver") === 'sync') {
                return;
            }

            // A dead queue trips the breaker too, so later logs skip it.
            if (!$failureRecorded) {
                $this->recordFailure($e);
            }

            // If dispatching fails, try the fallback channel
            $this->writeFallback('error', 'LogShipper failed to dispatch job', [
                'exception' => $e->getMessage(),
                'original_payload' => $sanitizedPayload,
            ], $e->getMessage());
        }
    }

    /**
     * Write to the fallback channel, tagged so the handler never ships it.
     */
    protected function writeFallback(string $level, string $message, array $context, string $reason): void
    {
        $fallbackChannel = config('log-shipper.fallback_channel');

        // CRITICAL: Prevent infinite loop if fallback channel is log_shipper
        if ($fallbackChannel && $fallbackChannel !== 'log_shipper') {
            $context['log_shipper_failure'] = $reason;

            try {
                Log::channel($fallbackChannel)->log($level, $message, $context);
            } catch (Throwable) {
                // If fallback fails, we really can't do anything else.
            }
        }
    }

    protected function isRecursiveLog(LogRecord $record): bool
    {
        // PERFORMANCE: Only check error/warning logs (debug/info unlikely to be recursive)
        if ($record->level->value < Level::Warning->value) {
            return false;
        }

        // Any of the package's jobs (ShipLogJob, ShipBatchJob, ShipStatusJob)
        $namespace = 'AdminIntelligence\LogShipper\Jobs\\';
        static $jobsDir = null;
        $jobsDir ??= dirname((new ReflectionClass(ShipLogJob::class))->getFileName()) . DIRECTORY_SEPARATOR;

        // Check if the message mentions a job class
        if (str_contains($record->message, $namespace)) {
            return true;
        }

        // Check if the exception context comes from the job
        if (isset($record->context['exception']) && $record->context['exception'] instanceof Throwable) {
            $exception = $record->context['exception'];

            // Check trace string
            $trace = $exception->getTraceAsString();
            if (str_contains($trace, $namespace)) {
                return true;
            }

            // Also check trace array for file paths
            foreach ($exception->getTrace() as $frame) {
                if (isset($frame['file']) && str_starts_with($frame['file'], $jobsDir)) {
                    return true;
                }
                if (isset($frame['class']) && str_starts_with($frame['class'], $namespace)) {
                    return true;
                }
            }
        }

        return false;
    }

    protected function buildPayload(LogRecord $record): array
    {
        $contextConfig = config('log-shipper.send_context', []);

        $payload = [
            'level' => strtolower($record->level->name),
            'message' => $record->message,
            'context' => $this->filterSerializable($record->context),
            // UTC with offset: the server stores the wall time it parses, so a local time would shift
            'datetime' => $record->datetime->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d\TH:i:s.uP'),
            'channel' => $record->channel,
            'extra' => $this->filterSerializable($record->extra),
        ];

        // The log server reads the stack frames from context['trace']
        $exception = $record->context['exception'] ?? null;
        if ($exception instanceof Throwable && !isset($payload['context']['trace'])) {
            $payload['context']['trace'] = $this->traceFrames($exception);
        }

        // Add request context if available and configured
        if ($this->shouldSendContext('user_id', $contextConfig)) {
            $payload['user_id'] = $this->safeGetUserId();
        }

        if ($this->shouldSendContext('ip_address', $contextConfig)) {
            $ip = $this->safeGetRequestData('ip');
            if ($ip !== null && config('log-shipper.ip_obfuscation.enabled', false)) {
                $method = config('log-shipper.ip_obfuscation.method', 'mask');
                $ip = IpObfuscator::obfuscate($ip, $method);
            }
            $payload['ip_address'] = $ip;
        }

        if ($this->shouldSendContext('user_agent', $contextConfig)) {
            $payload['user_agent'] = $this->safeGetRequestData('userAgent');
        }

        if ($this->shouldSendContext('request_method', $contextConfig)) {
            $method = $this->safeGetRequestData('method');
            $payload['request_method'] = in_array($method, self::REQUEST_METHODS, true) ? $method : null;
        }

        if ($this->shouldSendContext('request_url', $contextConfig)) {
            $payload['request_url'] = $this->safeGetRequestData('fullUrl');
        }

        if ($this->shouldSendContext('route_name', $contextConfig)) {
            $payload['route_name'] = $this->safeGetRouteData('name');
        }

        if ($this->shouldSendContext('controller_action', $contextConfig)) {
            $payload['controller_action'] = $this->safeGetRouteData('action');
        }

        if ($this->shouldSendContext('app_env', $contextConfig)) {
            $payload['app_env'] = config('app.env');
        }

        if ($this->shouldSendContext('app_debug', $contextConfig)) {
            $payload['app_debug'] = config('app.debug');
        }

        if ($this->shouldSendContext('referrer', $contextConfig)) {
            $payload['referrer'] = $this->safeGetRequestData('referrer');
        }

        return $payload;
    }

    protected function shouldSendContext(string $key, array $config): bool
    {
        return $config[$key] ?? false;
    }

    protected function safeGetUserId(): ?string
    {
        try {
            $id = Auth::id();

            return $id !== null ? (string) $id : null;
        } catch (Throwable) {
            return null;
        }
    }

    protected function safeGetRequestData(string $type): ?string
    {
        try {
            return match ($type) {
                'ip' => Request::ip(),
                'userAgent' => Request::userAgent(),
                'method' => Request::method(),
                'fullUrl' => Request::fullUrl(),
                'referrer' => Request::header('referer'),
                default => null,
            };
        } catch (Throwable) {
            return null;
        }
    }

    protected function safeGetRouteData(string $type): ?string
    {
        try {
            $route = Route::current();
            if (!$route) {
                return null;
            }

            return match ($type) {
                'name' => $route->getName(),
                'action' => $route->getActionName(),
                default => null,
            };
        } catch (Throwable) {
            return null;
        }
    }

    protected function sanitize(array $data): array
    {
        return Sanitizer::sanitize($data, config('log-shipper.sanitize_fields', []));
    }

    protected function normalizeThrowable(Throwable $e, int $depth = 0): array
    {
        $lines = [];
        foreach ($this->traceFrames($e) as $i => $frame) {
            $lines[] = sprintf(
                '#%d %s:%s %s%s%s()',
                $i,
                $frame['file'] ?? '[internal]',
                $frame['line'] ?? '?',
                $frame['class'] ?? '',
                $frame['type'] ?? '',
                $frame['function'] ?? ''
            );
        }

        $data = [
            'class' => $e::class,
            'message' => $e->getMessage(),
            'code' => $e->getCode(),
            'file' => $e->getFile(),
            'line' => $e->getLine(),
            'trace' => implode("\n", $lines),
        ];

        if ($depth < self::MAX_PREVIOUS_DEPTH && $e->getPrevious() !== null) {
            $data['previous'] = $this->normalizeThrowable($e->getPrevious(), $depth + 1);
        }

        return $data;
    }

    /**
     * Stack frames without args: args can hold secrets and huge objects.
     */
    protected function traceFrames(Throwable $e): array
    {
        return array_map(
            fn (array $frame) => array_intersect_key($frame, array_flip(['file', 'line', 'class', 'type', 'function'])),
            array_slice($e->getTrace(), 0, self::MAX_TRACE_FRAMES)
        );
    }

    protected function filterSerializable(array $data): array
    {
        $filtered = [];

        foreach ($data as $key => $value) {
            // Skip closures and resources
            if ($value instanceof Closure || is_resource($value)) {
                $filtered[$key] = '[FILTERED: ' . gettype($value) . ']';

                continue;
            }

            // SECURITY: Skip PDO and database connection objects to prevent credential leaks
            if ($value instanceof PDO || $value instanceof PDOStatement) {
                $filtered[$key] = '[FILTERED: Database Connection]';

                continue;
            }

            // Skip Throwable objects to avoid serialization issues with stack traces
            if ($value instanceof Throwable) {
                $filtered[$key] = $this->normalizeThrowable($value);

                continue;
            }

            // Handle other objects that might not serialize properly
            if (is_object($value)) {
                if (method_exists($value, '__toString')) {
                    $filtered[$key] = (string) $value;
                } elseif ($value instanceof JsonSerializable) {
                    $filtered[$key] = $value->jsonSerialize();
                } else {
                    $filtered[$key] = '[OBJECT: ' . get_class($value) . ']';
                }

                continue;
            }

            // Recursively filter arrays
            if (is_array($value)) {
                $filtered[$key] = $this->filterSerializable($value);
            } else {
                $filtered[$key] = $value;
            }
        }

        return $filtered;
    }
}
